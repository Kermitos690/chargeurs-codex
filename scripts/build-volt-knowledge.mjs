import { readFile, mkdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const OUTPUT = path.join(ROOT, "functions/_generated/volt-knowledge.generated.js");

// Customer-facing Volt knowledge must be curated prose. Do not index React pages,
// backend code, admin code, hardware procedures, secrets, CI or migrations.
// Raw source files made the fallback capable of echoing implementation details.
const ALLOWED_FILES = [
  "docs/volt/customer-knowledge.md",
];
const MAX_FILE_BYTES = 160_000;
const CHUNK_SIZE = 1300;
const CHUNK_OVERLAP = 180;

async function exists(file) {
  try { await stat(file); return true; } catch { return false; }
}

function cleanSource(raw) {
  return raw
    .replace(/\r/g, "")
    .replace(/https?:\/\/\S+/g, " ")
    .replace(/[ \t]+/g, " ")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function chunkText(source, text) {
  const chunks = [];
  let cursor = 0;
  let index = 0;
  while (cursor < text.length) {
    let end = Math.min(text.length, cursor + CHUNK_SIZE);
    if (end < text.length) {
      const paragraph = text.lastIndexOf("\n\n", end);
      const sentence = text.lastIndexOf(". ", end);
      const split = Math.max(paragraph, sentence);
      if (split > cursor + Math.floor(CHUNK_SIZE * 0.55)) end = split + 1;
    }
    const content = text.slice(cursor, end).trim();
    if (content.length >= 80) chunks.push({ id: `${source}#${index}`, source, content });
    if (end >= text.length) break;
    cursor = Math.max(cursor + 1, end - CHUNK_OVERLAP);
    index += 1;
  }
  return chunks;
}

const chunks = [];
const indexedSources = [];
for (const source of ALLOWED_FILES) {
  const absolute = path.join(ROOT, source);
  if (!(await exists(absolute))) continue;
  const info = await stat(absolute);
  if (!info.isFile() || info.size > MAX_FILE_BYTES) continue;
  const cleaned = cleanSource(await readFile(absolute, "utf8"));
  if (cleaned.length < 80) continue;
  indexedSources.push(source);
  chunks.push(...chunkText(source, cleaned));
}

await mkdir(path.dirname(OUTPUT), { recursive: true });
const generated = `// AUTO-GENERATED by scripts/build-volt-knowledge.mjs.\n// Curated customer-safe sources only. Do not edit by hand.\nexport const VOLT_KNOWLEDGE_META = ${JSON.stringify({ generatedAt: new Date().toISOString(), sources: indexedSources }, null, 2)};\nexport const VOLT_KNOWLEDGE = ${JSON.stringify(chunks, null, 2)};\n`;
await writeFile(OUTPUT, generated, "utf8");
console.log(`[volt-knowledge] indexed ${indexedSources.length} curated sources / ${chunks.length} chunks`);
