import { readdir, readFile, mkdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const OUTPUT = path.join(ROOT, "functions/_generated/volt-knowledge.generated.js");

// Volt public knowledge is deliberately allowlisted. Never ingest the whole repo:
// backend functions, admin code, hardware procedures, secrets, CI and migrations
// are not appropriate context for a customer-facing assistant.
const ALLOWED_FILES = [
  "README.md",
  "src/pages/Index.tsx",
  "src/pages/Support.tsx",
  "src/pages/Partners.tsx",
  "src/pages/LegalPage.tsx",
  "src/lib/publicPricing.ts",
];
const ALLOWED_DIRS = [
  "src/pages/public",
  "src/components/public",
];
const ALLOWED_EXTENSIONS = new Set([".md", ".tsx", ".ts", ".txt"]);
const SENSITIVE_LINE = /(service[_-]?role|secret|password|private[_-]?key|api[_-]?key|authorization|bearer\s|x-kiosk-token|token_hash|supabase_service|process\.env|import\.meta\.env)/i;
const MAX_FILE_BYTES = 120_000;
const CHUNK_SIZE = 1300;
const CHUNK_OVERLAP = 180;

async function exists(file) {
  try { await stat(file); return true; } catch { return false; }
}

async function walk(relativeDir) {
  const absolute = path.join(ROOT, relativeDir);
  if (!(await exists(absolute))) return [];
  const entries = await readdir(absolute, { withFileTypes: true });
  const out = [];
  for (const entry of entries) {
    const rel = path.posix.join(relativeDir.replaceAll("\\", "/"), entry.name);
    if (entry.isDirectory()) out.push(...await walk(rel));
    else if (ALLOWED_EXTENSIONS.has(path.extname(entry.name))) out.push(rel);
  }
  return out;
}

function cleanSource(raw, source) {
  let text = raw.replace(/\r/g, "");
  if (/\.(ts|tsx)$/.test(source)) {
    text = text
      .replace(/^import[^;]+;\s*$/gm, "")
      .replace(/^export\s+/gm, "")
      .replace(/className=("[^"]*"|'[^']*'|\{`[^`]*`\})/g, "")
      .replace(/<\/?[A-Za-z][^>]*>/g, " ")
      .replace(/[{}();]/g, " ");
  }
  text = text
    .split("\n")
    .filter((line) => !SENSITIVE_LINE.test(line))
    .join("\n")
    .replace(/https?:\/\/\S+/g, " ")
    .replace(/[ \t]+/g, " ")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return text;
}

function chunkText(source, text) {
  const chunks = [];
  let cursor = 0;
  let index = 0;
  while (cursor < text.length) {
    let end = Math.min(text.length, cursor + CHUNK_SIZE);
    if (end < text.length) {
      const paragraph = text.lastIndexOf("\n\n", end);
      const sentence = text.lastIndexOf(". ", end);
      const split = Math.max(paragraph, sentence);
      if (split > cursor + Math.floor(CHUNK_SIZE * 0.55)) end = split + 1;
    }
    const content = text.slice(cursor, end).trim();
    if (content.length >= 80) chunks.push({ id: `${source}#${index}`, source, content });
    if (end >= text.length) break;
    cursor = Math.max(cursor + 1, end - CHUNK_OVERLAP);
    index += 1;
  }
  return chunks;
}

const candidates = [...ALLOWED_FILES];
for (const dir of ALLOWED_DIRS) candidates.push(...await walk(dir));

const unique = [...new Set(candidates)].sort();
const chunks = [];
const indexedSources = [];
for (const source of unique) {
  const absolute = path.join(ROOT, source);
  if (!(await exists(absolute))) continue;
  const info = await stat(absolute);
  if (!info.isFile() || info.size > MAX_FILE_BYTES) continue;
  const raw = await readFile(absolute, "utf8");
  const cleaned = cleanSource(raw, source);
  if (cleaned.length < 80) continue;
  indexedSources.push(source);
  chunks.push(...chunkText(source, cleaned));
}

await mkdir(path.dirname(OUTPUT), { recursive: true });
const generated = `// AUTO-GENERATED by scripts/build-volt-knowledge.mjs.\n// Public-safe sources only. Do not edit by hand.\nexport const VOLT_KNOWLEDGE_META = ${JSON.stringify({ generatedAt: new Date().toISOString(), sources: indexedSources }, null, 2)};\nexport const VOLT_KNOWLEDGE = ${JSON.stringify(chunks, null, 2)};\n`;
await writeFile(OUTPUT, generated, "utf8");
console.log(`[volt-knowledge] indexed ${indexedSources.length} sources / ${chunks.length} chunks`);
